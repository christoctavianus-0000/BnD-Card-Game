export function getCardImageUrl(cardId: number): string {
  const filename = CARD_IMAGE_FILES[cardId];
  if (!filename) {
    throw new Error(`Missing PNG asset mapping for card id: ${cardId}`);
  }
  const base = import.meta.env.BASE_URL || './';
  const normalizedBase = base.endsWith('/') ? base : `${base}/`;
  return `${normalizedBase}assets/cards/${filename}`;
}
