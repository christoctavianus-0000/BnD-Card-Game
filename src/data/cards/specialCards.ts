import type { FootprintPattern, SpecialCardData } from '../../types/bnd';

/**
 * Parses an authentic 4x4 card badge string from BD2 ("row0/row1/row2/row3")
 * where '.' = empty, '基' = Primary/Base square, and '支' = Secondary square.
 */
export function parseBadgeGrid(grid: string): FootprintPattern {
  const rows = grid.split('/');
  if (rows.length !== 4 || rows.some((r) => [...r].length !== 4)) {
    throw new Error(`Invalid 4x4 badge grid: ${grid}`);
  }

  let anchor: [number, number] | null = null;
  const secAbs: [number, number][] = [];

  for (let r = 0; r < 4; r++) {
    const chars = [...rows[r]];
    for (let c = 0; c < 4; c++) {
      const ch = chars[c];
      if (ch === '基') {
        anchor = [r, c];
      } else if (ch === '支') {
        secAbs.push([r, c]);
      }
    }
  }

  if (!anchor) {
    throw new Error(`Missing Primary square '基' in grid: ${grid}`);
  }

  const secondaries: [number, number][] = secAbs.map(([sr, sc]) => [
    sr - anchor![0],
    sc - anchor![1],
  ]);

  return { anchor, secondaries };
}

