export type MonsterTribe =
  | 'Humanoid'
  | 'Beast'
  | 'Insect'
  | 'Aquatic'
  | 'Plant'
  | 'Demon'
  | 'Undead'
  | 'Spirit';

export type MonsterTrait =
  | 'none'
  | 'extra_reinforce'
  | 'extra_weaken'
  | 'extra_both'
  | 'reverse_weaken';

export interface FootprintPattern {
  /** (row, col) of the Primary Square inside the 4x4 card badge (0..3, 0..3) */
  anchor: readonly [number, number];
  /** (dr, dc) offsets of Secondary Squares relative to the Primary Square (player orientation) */
  secondaries: readonly (readonly [number, number])[];
}

export interface MonsterCardData {
  id: number;
  code: string;
  name: string;
  jpName: string;
  category: 'Monster';
  tribe: MonsterTribe;
  firstPt: number;
  repeatPt: number;
  isStarter?: boolean;
  trait: MonsterTrait;
  traitText?: string;
  normal: FootprintPattern;
  reinforced: FootprintPattern;
  weakened: FootprintPattern;
  sourceHint: string;
}

